import { resolve } from 'node:path';
import { mkdirSync, existsSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Settings } from './config.js';
import { Store } from './store.js';
import { Service } from './service.js';
import { makeServer } from './server.js';
import { Telegram } from './telegram.js';
const root = fileURLToPath(new URL('../',import.meta.url));
const demo = process.argv.includes('--demo');
const data = resolve(root,'data',demo?'demo':'production'); mkdirSync(data,{recursive:true});
const settingsPath = demo ? resolve(data,'settings.json') : resolve(root,'config/settings.json');
if (demo && !existsSync(settingsPath)) copyFileSync(resolve(root,'config/demo.json'),settingsPath);
const settings = new Settings(settingsPath);
const admins = demo ? ['demo-admin'] : (process.env.ADMIN_IDS ?? '').split(',').filter(x=>/^\d+$/.test(x));
const token = process.env.ADMIN_TOKEN ?? '';
if (!demo && (!admins.length || token.length < 32)) throw Error('Заполните ADMIN_IDS и ADMIN_TOKEN (минимум 32 символа) в .env. Для демо используйте --demo.');
const store = new Store(resolve(data,'vpn.sqlite'));
const service = new Service(store,settings,admins);
if (demo) service.user('demo-user','Тестовый пользователь');
const host = process.env.HOST || '127.0.0.1', port = Number(process.env.PORT || 8787);
if (host !== '127.0.0.1') throw Error('MVP слушает только 127.0.0.1. Для внешнего доступа используйте проверенный HTTPS reverse proxy.');
const server = makeServer(service,{demo,adminToken:token,host,port,telegramLogin:{clientId:process.env.TELEGRAM_CLIENT_ID,clientSecret:process.env.TELEGRAM_CLIENT_SECRET,publicOrigin:process.env.PUBLIC_ORIGIN}});
server.listen(port,host,()=>console.log(`VPN PROJECT ${demo?'DEMO':'PRODUCTION'}: http://${host}:${port}\n${demo?'Только тестовые данные. Telegram и настоящий VPN не подключены.':settings.readiness() ?? 'Настройки заполнены.'}`));
const telegram = !demo && process.env.BOT_TOKEN ? new Telegram(process.env.BOT_TOKEN,service) : null;
if (telegram) telegram.poll().catch(()=>{console.error('Не удалось запустить Telegram. Проверьте токен, сеть и отсутствие webhook.');process.exitCode=1;server.close();clearInterval(timer);});
else if (!demo) console.log('BOT_TOKEN не задан: доступна только локальная админка.');
const timer = setInterval(()=>{try {service.tick(); if(telegram) void telegram.flush();}catch{console.error('Ошибка фонового задания; проверьте хранилище.');}},5000);
service.tick();
for (const signal of ['SIGINT','SIGTERM']) process.on(signal,()=>{clearInterval(timer);if(telegram)telegram.running=false;server.close(()=>{store.close();process.exit(0);});setTimeout(()=>process.exit(0),2000).unref();});
