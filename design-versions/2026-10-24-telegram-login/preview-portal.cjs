const {chromium}=require('playwright');
const {resolve}=require('node:path');
const {mkdirSync}=require('node:fs');
(async()=>{
const output=resolve(__dirname,'../artifacts');mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_PATH});
try{
  const ctx=await browser.newContext({viewport:{width:1440,height:1100},deviceScaleFactor:1});
  const page=await ctx.newPage(),errors=[],external=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:8787/'))external.push(r.url());});
  await page.goto('http://127.0.0.1:8787/');await page.locator('.price-card').last().waitFor();
  if(await page.locator('.price-card').count()!==4)throw Error('Missing plans');
  if(await page.locator('.price-card').nth(1).locator('.plan-price').innerText()!=='699 ₽')throw Error('Quarter price mismatch');
  if(await page.locator('.site-header nav').getByText('Как подключить',{exact:true}).count())throw Error('Old header item remains');
  await page.screenshot({path:resolve(output,'colors-home.jpg'),fullPage:true});
  const guest=await browser.newContext({viewport:{width:1440,height:1000}}),guestPage=await guest.newPage();
  await guestPage.goto('http://127.0.0.1:8787/account');await guestPage.locator('.login-card').waitFor();
  if(await guestPage.locator('.progress').count())throw Error('Guest account shows onboarding');
  await guestPage.screenshot({path:resolve(output,'colors-login.jpg'),fullPage:true});
  await guestPage.setViewportSize({width:390,height:844});
  if(await guestPage.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Login mobile overflow');
  await guestPage.screenshot({path:resolve(output,'colors-login-mobile.jpg'),fullPage:true});
  await guestPage.goto('http://127.0.0.1:8787/offer');await guestPage.locator('.offer-document').waitFor();await guest.close();
  await page.locator('[data-action="select"][data-plan="m3"]').click();
  await page.locator('.checkout-main').waitFor();
  await page.screenshot({path:resolve(output,'colors-payment.jpg'),fullPage:true});
  await page.locator('[data-action="demo-activate"]').click();
  await page.locator('.access-url').waitFor();
  if(await page.locator('.download-grid a').count()!==3)throw Error('Missing download links');
  await page.screenshot({path:resolve(output,'colors-connect.jpg'),fullPage:true});
  await page.locator('[data-action="dashboard"]').click();await page.locator('.calendar-count').waitFor();
  if(new URL(page.url()).pathname!=='/account')throw Error('Dashboard does not have a separate URL');
  if(await page.locator('.progress').count())throw Error('Dashboard contains onboarding steps');
  await page.screenshot({path:resolve(output,'colors-dashboard.jpg'),fullPage:true});
  await page.reload();await page.locator('.calendar-count').waitFor();
  await page.locator('[data-action="scenario"][data-scenario="short"]').click();await page.locator('.days-count').waitFor();
  await page.locator('[data-action="scenario"][data-scenario="long"]').click();await page.locator('.calendar-count').waitFor();
  await page.locator('[data-action="telegram"]').click();await page.locator('dialog[open]').waitFor();
  await page.getByRole('heading',{name:'Ваш аккаунт Telegram',exact:true}).waitFor();
  await page.locator('[data-action="close"]').click();
  await page.locator('[data-action="scenario"][data-scenario="devices-full"]').click();
  await page.locator('.device-count strong').filter({hasText:/^2$/}).waitFor();
  if(await page.locator('.device-count span').innerText()!=='из 2')throw Error('Device limit mismatch');
  await page.locator('#toast').waitFor({state:'hidden'});
  await page.setViewportSize({width:390,height:844});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Dashboard mobile overflow');
  await page.screenshot({path:resolve(output,'colors-dashboard-mobile.jpg'),fullPage:true});
  await page.locator('[data-action="scenario"][data-scenario="expired"]').click();await page.locator('.expired-title').waitFor();
  if(await page.locator('.quick-connect [data-action="copy"]').count())throw Error('Expired access can be copied');
  await page.locator('.account-identity [data-action="logout"]').click();await page.locator('.login-card').waitFor();
  if(await page.locator('.progress').count())throw Error('Logout shows onboarding');
  await page.goto('http://127.0.0.1:8787/');await page.locator('.price-card').last().waitFor();
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Landing mobile overflow');
  await page.screenshot({path:resolve(output,'colors-home-mobile.jpg'),fullPage:true});
  const other=await browser.newContext();const otherPage=await other.newPage();await otherPage.goto('http://127.0.0.1:8787/');await otherPage.locator('.price-card').last().waitFor();await other.close();
  if(external.length)throw Error('External loading dependency: '+external.join(', '));
  if(errors.length)throw Error(errors.join('\n'));
  console.log(JSON.stringify({ok:true,stages:4,plans:4,downloads:3,returningUser:'dashboard',shortAndCalendarCountdown:true,telegramPreview:true,expiredAccessProtected:true,mobileOverflow:false,externalRequests:external,browserErrors:errors,output},null,2));
}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
